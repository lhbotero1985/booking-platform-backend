// Store keeps the processed images. Local writes them to a directory of the server (decision of
// the user, 2026-11-27: the server's disk for now); an S3-compatible store (DigitalOcean Spaces)
// can replace it before PROD without touching the modules.
type Store interface {
	Put(ctx context.Context, key string, data []byte) error
	// Delete removes a stored image; a missing one is not an error.
	Delete(ctx context.Context, key string) error
}

// Folders of the keys.
const (
	FolderLogos     = "logos"
	FolderCovers    = "covers"
	FolderPortfolio = "portfolio"
)

// keyPattern: folder/business-id/image-id.ext, all generated by the server.
var keyPattern = regexp.MustCompile(`^(logos|covers|portfolio)/[0-9a-f-]{36}/[0-9a-f-]{36}\.(jpg|png)$`)

// NewKey returns a fresh key for an image of a business; never derived from the uploaded name.
func NewKey(folder string, businessID uuid.UUID, img Image) string {
	return fmt.Sprintf("%s/%s/%s.%s", folder, businessID, uuid.Must(uuid.NewV7()), img.Ext)
}

// ValidKey tells whether key has the shape NewKey produces.
func ValidKey(key string) bool { return keyPattern.MatchString(key) }

// baseURL is the public origin the URLs of the images start with (PUBLIC_API_URL); empty in
// tests (the URLs are then relative).
var baseURL string

// SetBaseURL sets the public origin of the API. Call once at startup.
func SetBaseURL(u string) { baseURL = strings.TrimRight(u, "/") }

// URL is the public address of a stored image ("" for no image).
func URL(key string) string {
	if key == "" {
		return ""
	}
	return baseURL + "/media/" + key
}

// Local stores images under a directory.
type Local struct{ dir string }

// NewLocal returns a store rooted at dir, created if missing (0750).
func NewLocal(dir string) (*Local, error) {
	if err := os.MkdirAll(dir, 0o750); err != nil {
		return nil, fmt.Errorf("media: directory %s: %w", dir, err)
	}
	return &Local{dir: dir}, nil
}

func (l *Local) path(key string) (string, error) {
	if !ValidKey(key) {
		return "", fmt.Errorf("media: invalid key %q", key)
	}
	return filepath.Join(l.dir, filepath.FromSlash(key)), nil
}

// Put writes the image atomically (temporary file, then rename).
func (l *Local) Put(_ context.Context, key string, data []byte) error {
	p, err := l.path(key)
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(p), 0o750); err != nil {
		return err
	}
	tmp, err := os.CreateTemp(filepath.Dir(p), ".upload-*")
	if err != nil {
		return err
	}
	defer func() { _ = os.Remove(tmp.Name()) }() // no-op after the rename
	if _, err := tmp.Write(data); err != nil {
		_ = tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmp.Name(), p)
}

// Delete implements Store.
func (l *Local) Delete(_ context.Context, key string) error {
	p, err := l.path(key)
	if err != nil {
		return err
	}
	if err := os.Remove(p); err != nil && !errors.Is(err, fs.ErrNotExist) {
		return err
	}
	return nil
}

// Handler serves GET /media/{key...}: public, immutable (a new upload gets a new key), and
// readable from the portal's domain (Cross-Origin-Resource-Policy: cross-origin).
func (l *Local) Handler() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		key := r.PathValue("key")
		p, err := l.path(key)
		if err != nil {
			httpx.WriteProblem(w, r, httpx.NewProblem(http.StatusNotFound, httpx.CodeNotFound, ""))
			return
		}
		f, err := os.Open(p) //nolint:gosec // the key matches keyPattern: no traversal
		if err != nil {
			httpx.WriteProblem(w, r, httpx.NewProblem(http.StatusNotFound, httpx.CodeNotFound, ""))
			return
		}
		defer func() { _ = f.Close() }()
		st, err := f.Stat()
		if err != nil || st.IsDir() {
			httpx.WriteProblem(w, r, httpx.NewProblem(http.StatusNotFound, httpx.CodeNotFound, ""))
			return
		}
		h := w.Header()
		h.Set("Content-Type", mime.TypeByExtension(filepath.Ext(p)))
		h.Set("Cache-Control", "public, max-age=31536000, immutable")
		h.Set("Cross-Origin-Resource-Policy", "cross-origin")
		http.ServeContent(w, r, "", st.ModTime(), f)
	})
}

// Errors of reading an upload.
var (
	ErrNotMultipart = errors.New("media: the request must be multipart/form-data")
	ErrTooLarge     = errors.New("media: the image is larger than 5 MiB")
	ErrMissingFile  = errors.New("media: the image field is missing")
)

// Upload is an image in a request, read only after the caller is authorized (a business of
// someone else is a 404 whatever the body).
type Upload struct {
	Read func() ([]byte, error)
	// Field returns a text field of the form ("" if absent); call it after Read.
	Field func(name string) string
}

// FromRequest reads the file field "image" of a multipart/form-data request.
func FromRequest(r *http.Request) Upload {
	var form *multipart.Form
	return Upload{
		Read: func() ([]byte, error) {
			mt, _, err := mime.ParseMediaType(r.Header.Get("Content-Type"))
			if err != nil || mt != "multipart/form-data" {
				return nil, ErrNotMultipart
			}
			r.Body = http.MaxBytesReader(nil, r.Body, MaxUploadBytes+1<<20)      // bounded even without the global limit
			if err := r.ParseMultipartForm(MaxUploadBytes + 1<<20); err != nil { //nolint:gosec // body bounded just above (MaxBytesReader) and by httpx.LimitBody
				var mbe *http.MaxBytesError
				if errors.As(err, &mbe) {
					return nil, ErrTooLarge
				}
				return nil, ErrMissingFile
			}
			form = r.MultipartForm
			files := form.File["image"]
			if len(files) != 1 {
				return nil, ErrMissingFile
			}
			if files[0].Size > MaxUploadBytes {
				return nil, ErrTooLarge
			}
			f, err := files[0].Open()
			if err != nil {
				return nil, ErrMissingFile
			}
			defer func() { _ = f.Close() }()
			data, err := io.ReadAll(io.LimitReader(f, MaxUploadBytes+1))
			if err != nil {
				return nil, ErrMissingFile
			}
			if len(data) > MaxUploadBytes {
				return nil, ErrTooLarge
			}
			return data, nil
		},
		Field: func(name string) string {
			if form == nil || len(form.Value[name]) == 0 {
				return ""
			}
			return form.Value[name][0]
		},
	}
}

// Bytes is an Upload of data already in memory (tests and internal callers).
func Bytes(data []byte, fields map[string]string) Upload {
	return Upload{Read: func() ([]byte, error) { return data, nil }, Field: func(n string) string { return fields[n] }}
}

// Problem maps an error of reading or processing an upload to its RFC 9457 problem; false if
// err is not one of them.
func Problem(err error) (httpx.Problem, bool) {
	field := func(code string) httpx.Problem {
		p := httpx.NewProblem(http.StatusBadRequest, httpx.CodeInvalidRequest, "the image is not valid")
		p.Errors = []httpx.FieldError{{Field: "image", Message: code}}
		return p
	}
	switch {
	case errors.Is(err, ErrNotMultipart):
		return httpx.NewProblem(http.StatusUnsupportedMediaType, httpx.CodeUnsupportedMedia, "send the image as multipart/form-data in the field \"image\""), true
	case errors.Is(err, ErrTooLarge):
		return httpx.NewProblem(http.StatusRequestEntityTooLarge, httpx.CodeBodyTooLarge, "the image must not exceed 5 MiB"), true
	case errors.Is(err, ErrMissingFile):
		return field("REQUIRED"), true
	case errors.Is(err, ErrUnsupported):
		return field("UNSUPPORTED_IMAGE"), true
	case errors.Is(err, ErrInvalid):
		return field("INVALID_IMAGE"), true
	case errors.Is(err, ErrTooBig):
		return field("IMAGE_TOO_BIG"), true
	}
	return httpx.Problem{}, false
}
